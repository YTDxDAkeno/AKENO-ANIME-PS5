# Writes assets/anime/sample/: a short, synthetic test series (two seasons,
# five episodes) made only from FFmpeg's built-in test sources and the Inter
# font - no third-party footage. It lets the console run the whole path
# offline: Anime -> series -> season -> episode -> native player -> subtitles
# -> next episode. catalog.json describes it in the AKENO catalogue format.
# Run from the repository root; needs ffmpeg with libx264 and drawtext.
set -euo pipefail
root=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)
out="$root/assets/anime/sample"
font="$root/assets/fonts/Inter-Bold.ttf"
ff=(ffmpeg -hide_banner -loglevel error -y -nostdin)
x264=(-c:v libx264 -preset veryslow -profile:v high -level 3.0 -pix_fmt yuv420p -crf 35 -g 50
    -threads 1 -bitexact -flags:v +bitexact)
aac=(-c:a aac -ac 2 -b:a 64k -ar 48000 -flags:a +bitexact)
rm -rf -- "$out"
mkdir -p "$out/media" "$out/thumbs" "$out/subs" "$out/art"

# season episode title source tone
episodes=(
    "1 1 First_Light testsrc2=size=640x360:rate=25 440"
    "1 2 Static gradients=size=640x360:rate=25:speed=0.015:c0=0x0b1730:c1=0xff7a3d:seed=3 523"
    "1 3 Relay smptehdbars=size=640x360:rate=25 587"
    "2 1 Return_Signal gradients=size=640x360:rate=25:speed=0.02:c0=0x0b1730:c1=0x4f8cff:seed=9 659"
    "2 2 Open_Channel testsrc=size=640x360:rate=25 698"
)
for entry in "${episodes[@]}"; do
    read -r season episode title source tone <<<"$entry"
    title=${title//_/ }
    name="s${season}e${episode}"
    label="AKENO TEST SERIES   S${season} E${episode}   ${title}"
    "${ff[@]}" -f lavfi -i "$source" \
        -f lavfi -i "sine=frequency=${tone}:sample_rate=48000:beep_factor=2" -t 15 \
        -vf "drawbox=y=ih-86:w=iw:h=86:color=black@0.55:t=fill,drawtext=fontfile=${font}:text='${label}':x=24:y=h-70:fontsize=24:fontcolor=white,drawtext=fontfile=${font}:text='%{pts\\:hms}':x=w-tw-24:y=24:fontsize=26:fontcolor=white:box=1:boxcolor=black@0.5:boxborderw=8" \
        "${x264[@]}" "${aac[@]}" -movflags +faststart -map_metadata -1 "$out/media/$name.mp4"
    "${ff[@]}" -ss 5 -i "$out/media/$name.mp4" -frames:v 1 -vf scale=480:270 -q:v 4 \
        -map_metadata -1 "$out/thumbs/$name.jpg"
    cat >"$out/subs/$name.en.vtt" <<VTT
WEBVTT

1
00:00:01.000 --> 00:00:04.500
AKENO test series - Season ${season}, Episode ${episode}: ${title}

2
00:00:05.000 --> 00:00:09.500
If you can read this line, subtitles work.

3
00:00:10.000 --> 00:00:14.500
<i>Picture, a steady tone with a beep each second, and this text.</i>
VTT
done

# Artwork: a poster (2:3) and a banner (16:9) drawn from a gradient.
"${ff[@]}" -f lavfi -i "gradients=size=460x690:c0=0x0b1730:c1=0x4f8cff:c2=0x9b7bff:x0=0:y0=0:x1=460:y1=690:seed=7" \
    -frames:v 1 -vf "drawtext=fontfile=${font}:text='SIGNAL':x=(w-tw)/2:y=h*0.58:fontsize=72:fontcolor=white,drawtext=fontfile=${font}:text='LIGHTS':x=(w-tw)/2:y=h*0.58+84:fontsize=72:fontcolor=white,drawtext=fontfile=${font}:text='AKENO TEST SERIES':x=(w-tw)/2:y=h*0.48:fontsize=24:fontcolor=white@0.85" \
    -q:v 3 -map_metadata -1 "$out/art/poster.jpg"
"${ff[@]}" -f lavfi -i "gradients=size=1280x720:c0=0x0b1730:c1=0x2e5bd6:c2=0x9b7bff:x0=0:y0=720:x1=1280:y1=0:seed=7" \
    -frames:v 1 -vf "drawtext=fontfile=${font}:text='SIGNAL LIGHTS':x=w*0.55:y=h*0.42:fontsize=64:fontcolor=white@0.9" \
    -q:v 4 -map_metadata -1 "$out/art/banner.jpg"

